#!/usr/bin/env node

/**
 * Pre-change TAC probe for model-family, version, and spelling equivalence.
 *
 * The cases were written before the frozen artifact was first scored. They are
 * deliberately outside the public 256-pair corpus and the negation probe.
 */

import { resolve } from "node:path";
const { loadScorer } = await import(
  import.meta.url.includes("/release/") ? "../harness/wasm-abi.mjs" : "../../../harness/wasm-abi.mjs"
);

if (!process.argv[2]) {
  console.error("usage: node 2026-08-29-model-aliases.mjs <scorer.wasm>");
  process.exit(2);
}

const CASES = [
  {
    id: "gpt4-joined",
    question: "What did the authorship detector conclude?",
    truth: "Verdict: AI-generated. Attribution: GPT-4. Confidence: 91%.",
    good: "AI-generated; model GPT4; confidence 91%.",
    bad: "AI-generated; model Claude; confidence 91%.",
  },
  {
    id: "gpt4o-spaced",
    question: "Which model generated the sample?",
    truth: "The sample is AI-generated. Model: GPT-4o.",
    good: "Machine-generated; model GPT 4o.",
    bad: "Machine-generated; model Claude 3.",
  },
  {
    id: "claude-version-punctuation",
    question: "Which model generated the sample?",
    truth: "The sample is AI-generated. Model: Claude 3.5 Sonnet.",
    good: "AI-generated; model Claude-3.5-Sonnet.",
    bad: "AI-generated; model Gemini-1.5-Pro.",
  },
  {
    id: "gemini-version-change",
    question: "Which model generated the sample?",
    truth: "The sample is AI-generated. Model: Gemini 1.5 Pro.",
    good: "AI-generated; model Gemini-1.5-Pro.",
    bad: "AI-generated; model Gemini-2.0-Pro.",
  },
  {
    id: "llama-size-change",
    question: "Which model generated the sample?",
    truth: "The sample is AI-generated. Model: Llama 3.1 70B.",
    good: "AI-generated; model Llama-3.1-70B.",
    bad: "AI-generated; model Llama-3.1-8B.",
  },
  {
    id: "vendor-and-model",
    question: "Which model generated the sample?",
    truth: "AI-generated; attributed to OpenAI GPT-4o.",
    good: "Machine-generated by OpenAI's GPT-4o.",
    bad: "Machine-generated by Anthropic's Claude 3.",
  },
  {
    id: "unknown-model",
    question: "Was a generative model detected?",
    truth: "The text is human-written; no model was identified.",
    good: "Human-authored; model unknown.",
    bad: "Human-authored; model GPT4.",
  },
  {
    id: "negated-attribution",
    question: "Was the synthetic text attributed to GPT-4?",
    truth: "The text is AI-generated but is not attributable to GPT-4.",
    good: "Machine-generated; attribution unknown.",
    bad: "Machine-generated; attributed to GPT4.",
  },
  {
    id: "gpt4o-format-only",
    question: "Which model generated the sample?",
    truth: "The sample is AI-generated. Model: GPT-4o.",
    good: "The sample is AI-generated. Model: GPT4o.",
    bad: "The sample is AI-generated. Model: GPT-3.5.",
  },
  {
    id: "model-family",
    question: "Which model family generated the sample?",
    truth: "The sample is AI-generated by the GPT-4 family.",
    good: "AI-generated; the model belongs to the GPT4 family.",
    bad: "AI-generated; the model belongs to the Claude family.",
  },
];

const scorer = await loadScorer(resolve(process.argv[2]), "frozen TAC scorer");
const rows = CASES.map((test) => {
  const exact = scorer.score(test.question, test.truth, test.truth);
  const good = scorer.score(test.question, test.truth, test.good);
  const bad = scorer.score(test.question, test.truth, test.bad);
  return { id: test.id, exact, good, bad, margin: good - bad, passed: good > bad };
});

for (const row of rows) {
  console.log(
    `${row.passed ? "PASS" : "FAIL"} ${row.id.padEnd(29)} ` +
      `exact=${row.exact.toFixed(6)} good=${row.good.toFixed(6)} ` +
      `bad=${row.bad.toFixed(6)} margin=${row.margin.toFixed(6)}`,
  );
}

const wins = rows.filter((row) => row.passed).length;
const meanMargin = rows.reduce((sum, row) => sum + row.margin, 0) / rows.length;
const worstMargin = Math.min(...rows.map((row) => row.margin));
console.log(
  `\nMODEL ALIAS PROBE: ${wins}/${rows.length} strict wins | ` +
    `mean margin ${meanMargin.toFixed(6)} | worst margin ${worstMargin.toFixed(6)}`,
);
process.exitCode = wins === rows.length ? 0 : 1;
