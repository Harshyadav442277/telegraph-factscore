/**
 * Out-of-corpus TAC metamorphic probes used on 2026-08-29.
 *
 * These are deliberately not loaded by the public benchmark. They exercise
 * semantic shapes absent from the frozen corpus, especially verdict negation,
 * alternate probability notation, and multi-axis sentences.
 */

