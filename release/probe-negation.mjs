const scorer = await loadScorer(WASM, "frozen TAC scorer");
const rows = [];
for (const test of CASES) {
  const good = scorer.score(test.question, test.truth, test.good);
  for (const badText of test.bad) {
    const bad = scorer.score(test.question, test.truth, badText);
    rows.push({ id: test.id, good, bad, margin: good - bad, passed: good > bad });
  }
}

for (const row of rows) {
  console.log(
    `${row.passed ? "PASS" : "FAIL"} ${row.id.padEnd(34)} ` +
      `good=${row.good.toFixed(6)} bad=${row.bad.toFixed(6)} margin=${row.margin.toFixed(6)}`,
  );
}
const wins = rows.filter((row) => row.passed).length;
const meanMargin = rows.reduce((sum, row) => sum + row.margin, 0) / rows.length;
const worstMargin = Math.min(...rows.map((row) => row.margin));
console.log(
  `\nUNSEEN TAC METAMORPHIC: ${wins}/${rows.length} strict wins | ` +
    `mean margin ${meanMargin.toFixed(6)} | worst margin ${worstMargin.toFixed(6)}`,
);
process.exitCode = wins === rows.length ? 0 : 1;
