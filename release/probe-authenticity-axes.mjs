#!/usr/bin/env node

/**
 * Pre-change semantic probe derived only from the public canonical intent:
 * genuine, original, or machine-generated. It deliberately keeps genuineness,
 * originality, integrity, and authorship as independent axes.
 */

import { resolve } from "node:path";
const { loadScorer } = await import(
  import.meta.url.includes("/release/") ? "../harness/wasm-abi.mjs" : "../../../harness/wasm-abi.mjs"
);

if (!process.argv[2]) {
  console.error("usage: node 2026-08-29-authenticity-axes.mjs <scorer.wasm>");
  process.exit(2);
}

const CASES = [
  ["genuine", "Is the supplied letter genuine?", "The letter is authentic and genuine.", "It is a legitimate, authentic letter.", "It is fabricated and fake."],
  ["fabricated", "Is the quotation authentic?", "The quotation is fabricated, not genuine.", "It is a forged quotation.", "It is authentic and real."],
  ["original", "Is the essay original?", "The essay is original and was not copied.", "It is independently written, not plagiarized.", "It is copied from another essay."],
  ["plagiarized", "Is the submission original?", "The submission is plagiarized and not original.", "It is copied material.", "It is an original composition."],
  ["authentic-copy", "Is this the original manuscript?", "This is an authentic copy, but it is not the original manuscript.", "It is a genuine duplicate, not the original.", "It is the original manuscript."],
  ["original-fake-attribution", "Is this a genuine historical quotation?", "The wording is original, but the historical attribution is fabricated and not genuine.", "It is newly composed but falsely attributed.", "It is an authentic historical quotation."],
  ["unaltered", "Was the document modified?", "The document is intact and unaltered.", "No tampering or editing was detected.", "The document was modified."],
  ["tampered", "Is the file unchanged?", "The file was altered and tampered with.", "It has been edited and is not intact.", "It is unchanged and unaltered."],
  ["human", "Who wrote the passage?", "The passage was written by a human, not generated by AI.", "A person authored it.", "It was machine-generated."],
  ["machine", "Who wrote the response?", "The response was generated by an AI system, not a person.", "It is machine-generated.", "It is human-authored."],
  ["mixed-authorship", "Was the article entirely AI-generated?", "The article combines human writing with AI-assisted edits; it is not entirely AI-generated.", "It has mixed human and AI authorship.", "It was entirely generated by AI."],
  ["inconclusive", "Is the text authentic?", "The available evidence is inconclusive; authenticity could not be verified.", "Authenticity remains unverified and unknown.", "The text is definitely genuine."],
  ["verified-source", "Is the attributed source genuine?", "The source attribution was verified as genuine.", "The attribution is authentic and verified.", "The attribution is forged."],
  ["unverified-source", "Was the source verified?", "The source could not be verified and may be fabricated.", "The attribution remains unverified.", "The source is confirmed genuine."],
  ["no-plagiarism", "Was plagiarism detected?", "No plagiarism was detected; the text is original.", "The work is not copied.", "The work is plagiarized."],
  ["genuine-ai", "Is the published statement authentic and who wrote it?", "The publication is genuine, but its text was generated by AI.", "It is an authentic publication containing machine-generated text.", "It is a fake publication written by a human."],
  ["copied-human", "Is this human writing original?", "A human wrote the passage, but it was copied and is not original.", "It is human-authored plagiarism.", "It is an original human composition."],
  ["paraphrase", "Is the answer copied verbatim?", "The answer is a human-written paraphrase, not a verbatim copy.", "A person rewrote it; it was not copied word for word.", "It is a verbatim duplicate."],
  ["confidence-scale", "How confident is the authenticity finding?", "The text is genuine with 92% confidence.", "Authentic; probability 0.92.", "Authentic; probability 0.08."],
  ["partial-edit", "Is the document wholly fabricated?", "The original document is genuine, although one paragraph was edited.", "Mostly authentic with a limited alteration.", "The entire document is fabricated."],
].map(([id, question, truth, good, bad]) => ({ id, question, truth, good, bad }));

const scorer = await loadScorer(resolve(process.argv[2]), "TAC authenticity-axis scorer");
const showBreakdown = process.argv.includes("--breakdown");
const rows = CASES.map((test) => {
  const good = scorer.score(test.question, test.truth, test.good);
  const bad = scorer.score(test.question, test.truth, test.bad);
  const breakdown = showBreakdown ? scorer.breakdown(test.question, test.truth, test.good) : null;
  return { id: test.id, good, bad, margin: good - bad, passed: good > bad, breakdown };
});

for (const row of rows) {
  console.log(`${row.passed ? "PASS" : "FAIL"} ${row.id.padEnd(27)} good=${row.good.toFixed(6)} bad=${row.bad.toFixed(6)} margin=${row.margin.toFixed(6)}`);
  if (row.breakdown) console.log(`     ${Object.entries(row.breakdown).map(([key, value]) => `${key}=${value.toFixed(6)}`).join(" ")}`);
}

const wins = rows.filter((row) => row.passed).length;
const meanMargin = rows.reduce((sum, row) => sum + row.margin, 0) / rows.length;
console.log(`\nAUTHENTICITY AXES: ${wins}/${rows.length} strict wins | mean margin ${meanMargin.toFixed(6)}`);
process.exitCode = wins === rows.length ? 0 : 1;
