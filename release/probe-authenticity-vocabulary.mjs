#!/usr/bin/env node

/**
 * Pre-change vocabulary probe derived from the public TAC definition. These
 * are ordinary paraphrases of authorship, originality, genuineness, integrity,
 * and verification—not observed Telegraph fixtures.
 */

import { resolve } from "node:path";
const { loadScorer } = await import(
  import.meta.url.includes("/release/") ? "../harness/wasm-abi.mjs" : "../../../harness/wasm-abi.mjs"
);

if (!process.argv[2]) {
  console.error("usage: node 2026-08-29-authenticity-vocabulary.mjs <scorer.wasm>");
  process.exit(2);
}

const CASES = [
  ["manual-authorship", "Who authored this?", "A human wrote the text; it was not automated.", "It was manually composed.", "It was produced automatically."],
  ["algorithmic-authorship", "Was this produced by a person?", "The response was generated by a machine, not written by a person.", "It was algorithmically produced.", "It was manually written."],
  ["unique-original", "Is this wording original?", "The wording is original and not copied.", "It is a unique composition.", "It was reproduced from another source."],
  ["lifted-copy", "Was the passage copied?", "The passage was copied and is not original.", "It was lifted from another publication.", "It is uniquely composed."],
  ["bona-fide", "Is the certificate genuine?", "The certificate is authentic, not fake.", "It is bona fide.", "It is a hoax."],
  ["fraudulent", "Is the notice authentic?", "The notice is fabricated and inauthentic.", "It is fraudulent and bogus.", "It is bona fide."],
  ["falsified", "Is the record genuine?", "The record is fake and forged.", "It was falsified.", "It is legitimate."],
  ["pristine", "Was the file changed?", "The file is intact and unmodified.", "It remains pristine.", "It was doctored."],
  ["doctored", "Was this image altered?", "The image was manipulated and edited.", "It was doctored.", "It remains pristine."],
  ["redacted", "Is the document unchanged?", "The document was modified and is not intact.", "It was redacted and revised.", "It is pristine."],
  ["undetermined", "Was authenticity established?", "The result is inconclusive and unverified.", "The finding is undetermined.", "It was proven genuine."],
  ["authenticated", "Was the source verified?", "The source was verified and confirmed.", "It was authenticated and proven.", "It remains unconfirmed."],
].map(([id, question, truth, good, bad]) => ({ id, question, truth, good, bad }));

const scorer = await loadScorer(resolve(process.argv[2]), "TAC vocabulary scorer");
const rows = CASES.map((test) => {
  const good = scorer.score(test.question, test.truth, test.good);
  const bad = scorer.score(test.question, test.truth, test.bad);
  return { id: test.id, good, bad, margin: good - bad, passed: good > bad };
});

for (const row of rows) {
  console.log(`${row.passed ? "PASS" : "FAIL"} ${row.id.padEnd(24)} good=${row.good.toFixed(6)} bad=${row.bad.toFixed(6)} margin=${row.margin.toFixed(6)}`);
}

const wins = rows.filter((row) => row.passed).length;
const meanMargin = rows.reduce((sum, row) => sum + row.margin, 0) / rows.length;
console.log(`\nAUTHENTICITY VOCABULARY: ${wins}/${rows.length} strict wins | mean margin ${meanMargin.toFixed(6)}`);
process.exitCode = wins === rows.length ? 0 : 1;
